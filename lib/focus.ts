/* iCITY 113Н — программная установка фокуса без кольца.
   Путь в проекте: lib/focus.ts

   ЧТО ЧИНИТ. Оверлеи двигают фокус сами: открывая план — на «Закрыть»,
   закрывая — обратно на «Открыть планировку». Если это приходится сразу
   после нажатия клавиши (а Esc — это оно и есть), браузер засчитывает
   такой программный фокус за клавиатурную навигацию, и `:focus-visible`
   срабатывает. Глобальное правило из tokens.css рисует по нему
   `outline: 2px solid var(--ink)` со сдвигом 2 px — почти чёрную рамку
   поверх фотографии зоны. Замер настоящей клавишей на кнопке «Закрыть»:
   `:focus-visible === true`, `outline` 2 px `rgb(16, 22, 25)`.

   ЧЕГО НЕ ДЕЛАЕМ. Не убираем сам перенос фокуса: без него Tab начинал бы
   обход с начала страницы, а стрелки между зонами перестали бы работать
   вовсе — они слушают корень офиса и только при фокусе внутри него.
   И не глушим кольцо через `outline: none` — оно обязано появляться,
   когда зритель действительно пришёл сюда Tab-ом.

   ЧТО ДЕЛАЕМ. Опция `focusVisible: false` ровно для этого и существует:
   «поставь фокус, но не показывай кольцо — сюда не приходили с клавиатуры».
   Настоящая клавиатурная навигация кольцо по-прежнему получает.

   ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ШЕСТЬ ПРИВЕДЕНИЙ ПО МЕСТАМ. В lib.dom.d.ts
   у FocusOptions поля `focusVisible` ещё нет, и без обёртки в каждой из
   шести точек пришлось бы писать `as` — шесть мест, где легко потерять
   опцию при следующей правке, и ни одного, где записано зачем.

   `preventScroll` здесь всегда: три из шести вызовов и раньше его несли,
   а без него браузер подтягивает страницу к цели и отменяет только что
   сделанный программный переезд (см. closePlan в OfficeHub).

   ОГОВОРКА ПРО SAFARI. Там `focusVisible` поддержан хуже, и кольцо может
   вернуться. Для кнопки плана это не страшно — её состояния держатся
   на `:focus-visible` в CSS и от опции не зависят. У «Закрыть»
   подстраховки нет: если кольцо там снова появится, лечить надо будет
   заменой в её собственном CSS, а не общим `outline: none`. */

/** FocusOptions с focusVisible: в стандартных типах его пока нет. */
type QuietFocusOptions = FocusOptions & { focusVisible?: boolean };

/**
 * Поставить фокус, не рисуя кольцо фокуса.
 * Для программных переносов — возврат после закрытия оверлея,
 * автофокус на кнопке закрытия, перенос на контент после hero.
 */
export function focusQuietly(el: HTMLElement | null | undefined): void {
  el?.focus({ preventScroll: true, focusVisible: false } as QuietFocusOptions);
}
