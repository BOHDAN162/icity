/* --- тач: страницу на телефоне везём сами --------------------------
   ДО ЭТОГО ТАЧ НЕ СЛУШАЛИ ВОВСЕ, и это было правило, а не пробел:
   инерция на телефоне системная, считает её компоситор, и любая наша
   поверх неё читается как подтормаживание. Богдан попросил всё равно
   (4 сентября 2026), цена показана и принята.

   ЧЕМ ПЛАТИМ, чтобы не выяснять это заново через полгода:
   — адресная строка iOS перестаёт убираться при прокрутке. Она
     реагирует на НАТИВНЫЙ скролл, а нативного больше нет. Это самая
     заметная потеря, и обойти её нельзя ничем, кроме отката;
   — пропадает «резинка» на краях. Pull-to-refresh при этом не теряем:
     его и так гасит overscroll-behavior-y: none в tokens.css;
   — ход становится зависим от главного потока.

   ВЫКЛЮЧЕНО В ТОТ ЖЕ ДЕНЬ, по той же причине, что и трекпад: чтобы
   вести палец самим, нужен touchmove с passive: false, а это снимает
   прокрутку с компоситора и кладёт на главный поток. На телефоне,
   где поток слабее, цена выше вдвойне. Системная инерция iOS считается
   вне главного потока и остаётся самым плавным, что здесь возможно.

   Код привода оставлен целиком: он рабочий, проверен замерами
   (свайп 1:1, флик с конечным хвостом) и включается одним словом.
   Но включать его стоит только после того, как стоимость кадра
   на телефоне измерена и признана низкой.

   ФЛАГ ЧИТАЕТСЯ И ПЕРЕД addEventListener, не только внутри
   обработчиков. Непассивный touchmove снимает прокрутку с компоситора
   САМИМ ФАКТОМ РЕГИСТРАЦИИ: браузер не знает заранее, позовём ли мы
   preventDefault, и обязан дождаться главного потока. Ранний return
   внутри обработчика от этого не спасает — решение принято до его
   вызова. Полдня этот флаг стоял в false, а цену свою страница всё
   равно платила. */
export const SCROLL_SMOOTH_TOUCH = false;

