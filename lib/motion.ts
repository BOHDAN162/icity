export const PLAN_HOME_EL = 51;

/* --- план за указателем ---------------------------------------------- */

/* ЭТО НАКЛОН ПЛИТЫ, А НЕ ОБЛЁТ КАМЕРОЙ. План — плоская плита на
   центральной оси, указатель притягивает ближнюю к себе кромку: она
   опускается, противоположная поднимается. Плита клонится к курсору.

   Облёт читался бы наоборот. Уводя камеру влево, мы показываем больше
   правой стороны плана, и левая кромка кажется поднявшейся — ровно
   противоположное тому, что нужно. Поэтому камера стоит неподвижно,
   а поворачивается группа вокруг собственного центра.

   PLAN_POINTER_AZ — наклон от ГОРИЗОНТАЛЬНОГО смещения указателя:
     курсор левее центра → левая кромка вниз, правая вверх;
     курсор правее       → правая вниз, левая вверх.

   PLAN_POINTER_EL — наклон от ВЕРТИКАЛЬНОГО смещения указателя:
     курсор выше центра  → дальняя кромка уходит вниз, от зрителя;
     курсор ниже         → ближняя кромка опускается к зрителю.

   Оси наклона берутся от камеры, а не от мира: экранное «влево» при
   азимуте 61° не совпадает ни с осью X, ни с осью Z, и наклон вокруг
   мировых осей поехал бы вкось. Знаки выводятся из векторов камеры
   в PlanScene, а не подбираются.

   Четыре градуса и два с половиной — меньше, чем даёт праздношатание,
   и это специально: слежение не перебивает покой, оно его подталкивает. */
export const PLAN_POINTER_AZ = 4;
export const PLAN_POINTER_EL = 2.5;

/* Доля, на которую значение подтягивается к цели за кадр. 0,06 — это
   около 300 мс на установление: план идёт за курсором с заметным
   отставанием, а не прилипает к нему. Оно же ограничитель — резкий мах
   мышью не может швырнуть сцену, догоняет она всегда с этой скоростью. */
export const PLAN_EASE = 0.06;

