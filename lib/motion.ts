export const SCROLL_LINE_PX = 16;

/* Запасной признак мыши, когда wheelDeltaY не помог: одиночный крупный
   КРУГЛЫЙ шаг. Работает потому, что тип решается по ПЕРВОМУ событию
   жеста, а первое событие — единственное место, где мышь и трекпад
   расходятся заведомо: у мыши это сразу полный щелчок, у трекпада жест
   всегда начинается с малого — палец трогается с места. */
export const SCROLL_MOUSE_MIN_PX = 50;

/**
 * Мышь или трекпад. Спрашивать ТОЛЬКО у первого события жеста.
 *
 * `deltaMode ≠ 0` — «строки» или «страницы»; так шлёт только мышь,
 * и этим закрыт Firefox, где `wheelDeltaY` не существует вовсе.
 * Кратность `wheelDeltaY` ста двадцати — канонический признак щелчка
 * колеса в Chrome и Safari: у трекпада там произвольное число.
 * Запасной признак — крупный круглый целый шаг: щелчки бывают 40, 100
 * и 120 px, а быстрый мах пальцем даёт величину случайную.
 *
 * Проверять функцией, а не в компоненте: синтетика CDP всем событиям
 * ставит wheelDeltaY = −120, и через браузерный замер эти ветки
 * не различить — они проверяются вызовом напрямую.
 */
export const wheelLooksLikeMouse = (
  e: Pick<WheelEvent, 'deltaMode' | 'deltaY'> & { wheelDeltaY?: number },
): boolean => {
  if (e.deltaMode !== 0) return true;
  const wd = e.wheelDeltaY;
  if (typeof wd === 'number' && wd !== 0 && Math.abs(wd) % 120 === 0) return true;
  const d = Math.abs(e.deltaY);
  return Number.isInteger(d) && d >= SCROLL_MOUSE_MIN_PX && d % 10 === 0;
};

/* ЭКСПОНЕНТА НЕ ДОЕЗЖАЕТ, И ЭТО НЕ МЕЛОЧЬ. Замер до правки: жест в 300 мс
   давал хвост 1927 мс, и в нём 22 % кадров стояли на месте — страница
   не ехала, а тикала по полпикселя раз в семь кадров. Ровно это и
   читается как подёргивание.

   Поэтому у шага есть пол: как только сглаживание просит меньше одного
   ФИЗИЧЕСКОГО пикселя, скорость перестаёт падать и остаток проходится
   ровно этим шагом. Меньше нельзя — экран не покажет; больше не нужно —
   это и есть самое мелкое видимое движение. Хвост становится конечным
   (около 175 мс на 120 Гц) и все его кадры — движущиеся.

   В физических пикселях, а не в css: на Retina один css-пиксель — это
   два экранных, и порог в 1 css px оставил бы половину хвоста
   по-прежнему прыгающей через кадр. Делится на devicePixelRatio
   в компоненте. */
export const SCROLL_MIN_STEP_DPX = 1;

