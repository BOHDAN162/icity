/* iCITY 113Н — амплитуды движения, отвечающего на зрителя.
   Путь в проекте: lib/motion.ts

   ВСЁ, ЧТО КРУТЯТ ПОСЛЕ ЖИВОГО ПРОСМОТРА, ЛЕЖИТ ЗДЕСЬ. Три поведения —
   план за курсором, план за пальцем, параллакс за наклоном телефона —
   делят одни константы, чтобы читались как одно поведение, а не как три
   разных эффекта, случайно оказавшихся на одной странице.

   ОБЩЕЕ ПРАВИЛО АМПЛИТУД. Страницу открывают на переговорах. Движение
   должно читаться как глубина, когда его заметили, и быть незаметным,
   когда не заметили. Сомневаешься — уменьшай.

   ЕДИНИЦЫ. Углы в градусах, доли — от нуля до единицы за кадр,
   время в миллисекундах. */

/* Домашняя высота камеры. Нужна и сцене, и рамкам доворота: без неё
   ограничения пришлось бы дублировать числом в двух местах. */
export const PLAN_HOME_EL = 51;

/* --- план за указателем ---------------------------------------------- */

/* Полный размах указателя от центра к краю окна доворачивает план на
   столько градусов. Четыре и два с половиной — это меньше, чем даёт
   праздношатание, и специально: слежение не должно перебивать покой,
   оно должно его чуть подталкивать. */
export const PLAN_POINTER_AZ = 4;
export const PLAN_POINTER_EL = 2.5;

/* Доля, на которую значение подтягивается к цели за кадр. 0,06 — это
   около 300 мс на установление: план идёт за курсором с заметным
   отставанием, а не прилипает к нему. Оно же ограничитель — резкий мах
   мышью не может швырнуть сцену, догоняет она всегда с этой скоростью. */
export const PLAN_EASE = 0.06;

/* --- праздношатание --------------------------------------------------- */

/* ±5,5° за 26 секунд: сцена не кажется картинкой и никого не укачивает.
   Пока указатель в секции, качание глушится до нуля и возвращается,
   когда он ушёл, — плавно, той же долей за кадр, а не рывком. */
export const PLAN_IDLE_AMP = 5.5;
export const PLAN_IDLE_PERIOD = 26000;

/* --- перетаскивание --------------------------------------------------- */

/* Палец и курсор ведут план через ОДНУ огибающую — ту же, что выше.
   Свайп через половину секции доворачивает ровно настолько же, насколько
   курсор, уведённый в край. Это сделано нарочно: два ввода должны
   читаться как одно поведение, а не как «на мыши чуть-чуть, а пальцем
   можно раскрутить».

   Свободной орбиты на ±28°, которая была здесь раньше, больше нет.
   Если после живого просмотра захочется вернуть возможность обойти план
   кругом — поднимать PLAN_POINTER_AZ, а не заводить второй механизм. */

/* Рамки высоты камеры. Страховочные: при нынешних амплитудах до них
   не дотянуться, но они не дают плану перевернуться, если амплитуды
   поднимут. */
export const PLAN_DRAG_EL_MIN = 26;
export const PLAN_DRAG_EL_MAX = 64;

/* Сдвиг меньше — это тап, а не перетаскивание, и зона выбирается как
   обычно. Порог живёт и на мыши, и на пальце: палец всегда чуть ползёт,
   и без порога ни один тап по зоне не дошёл бы до цели. */
export const PLAN_DRAG_SLOP = 6;

/* --- параллакс кадров зон -------------------------------------------- */

/* Максимальный сдвиг кадра в экранных пикселях на полный размах ввода.
   У кухни тише: её передний план сидит в 7,2 раза выше медианы кадра,
   и на общей амплитуде ближняя перегородка ездила бы заметно сильнее
   всего остального. */
export const PARALLAX_AMPLITUDE = {
  openspace: 14,
  corridor: 14,
  kitchen: 10,
  reception: 14,
  meeting_lg: 14,
} as const;

/* Сглаживание указателя и наклона: 0,08 — около 250 мс на установление. */
export const PARALLAX_EASE = 0.08;

/* --- наклон телефона -------------------------------------------------- */

/* Полный размах — пятнадцать градусов от того положения, в котором
   телефон держали в момент открытия зоны. Жёстко: телефон в живой руке
   даёт много шума, и широкий диапазон превращает параллакс в дрожь.

   Наклон считается ОТНОСИТЕЛЬНЫМ. Абсолютные значения означали бы, что
   эффект зависит от того, как человек держит аппарат: лёжа на диване
   кадр уехал бы в упор ещё до того, как зритель шевельнулся. */
export const TILT_RANGE = 15;

/* Наклон шумит сильнее мыши, поэтому сглаживается вдвое сильнее. */
export const TILT_EASE = 0.04;

/* --- состояние доворота плана ---------------------------------------- */

/* Одно состояние на три источника ввода: указатель, палец и покой.
   Живёт в ref и меняется каждый кадр, поэтому это не React-состояние —
   класть его в useState значило бы перерисовывать дерево шестьдесят раз
   в секунду ради числа, которое читает только камера.

   Слагаемые складываются, а не вытесняют друг друга: накопленный
   доворот пальцем остаётся, слежение за указателем добавляется сверху,
   праздношатание входит с весом, который гаснет, пока указатель
   в секции, и возвращается, когда он ушёл. */
export type PlanOrbit = {
  /** текущий доворот, градусы */
  ptrAz: number;
  ptrEl: number;
  /** куда слежение едет */
  tgtAz: number;
  tgtEl: number;
  /** вес праздношатания, 0…1, и его цель */
  idle: number;
  tgtIdle: number;
  dragging: boolean;
  /* Сколько пикселей проехал текущий жест. Порог тапа проверяет сцена,
     а слушатели живут в оболочке — значит, число должно быть общим. */
  moved: number;
  /* «Нарисуй кадр». Ставит сцена, зовёт оболочка. Через эту щель, а не
     импортом invalidate: оболочка обслуживает и плоский план, а он обязан
     стоить ноль байт three. */
  wake?: () => void;
};

const blank = (): PlanOrbit => ({
  ptrAz: 0,
  ptrEl: 0,
  tgtAz: 0,
  tgtEl: 0,
  idle: 1,
  tgtIdle: 1,
  dragging: false,
  moved: 0,
});

/* Один объект на модуль, а не проп и не ref, проброшенный через дерево.
   Так вышло не от лени: план на экране существует в единственном числе,
   а состояние меняется каждый кадр — прокинутый вниз ref пришлось бы
   мутировать из компонента, который его получил, и это ровно то, что
   React Compiler запрещает. Модульный объект честнее: и оболочка,
   и сцена обращаются к общему месту, никто ничего не «портит» в чужих
   пропсах. Сбрасывается при открытии плана. */
export const planOrbit: PlanOrbit = blank();

export const resetPlanOrbit = () => {
  Object.assign(planOrbit, blank(), { wake: planOrbit.wake });
};

const clamp = (n: number, a: number, b: number) => (n < a ? a : n > b ? b : n);

/** Указатель внутри секции: nx и ny — доли от центра к краю, −1…1. */
export const orbitFollow = (o: PlanOrbit, nx: number, ny: number) => {
  o.tgtAz = clamp(nx, -1, 1) * PLAN_POINTER_AZ;
  // Вверх по экрану — камера чуть выше: иначе движение читается наоборот
  o.tgtEl = -clamp(ny, -1, 1) * PLAN_POINTER_EL;
  o.tgtIdle = 0;
};

/** Указатель ушёл из секции: слежение к нулю, покой обратно к единице. */
export const orbitRelease = (o: PlanOrbit) => {
  o.tgtAz = 0;
  o.tgtEl = 0;
  o.tgtIdle = 1;
};

/** Шаг сглаживания. Возвращает true, пока что-то ещё едет. */
export const orbitStep = (o: PlanOrbit): boolean => {
  const daz = o.tgtAz - o.ptrAz;
  const del = o.tgtEl - o.ptrEl;
  const di = o.tgtIdle - o.idle;
  o.ptrAz += daz * PLAN_EASE;
  o.ptrEl += del * PLAN_EASE;
  o.idle += di * PLAN_EASE;
  return Math.abs(daz) > 0.002 || Math.abs(del) > 0.002 || Math.abs(di) > 0.002;
};

