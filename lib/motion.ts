/* Красная точка и тонкое кольцо вокруг неё вместо системной стрелки.
   Ведут их ДВА РАЗНЫХ сглаживания, и это главное в приёме: точка идёт
   почти за указателем, кольцо отстаёт и догоняет — отсюда читается
   инерция, а не «картинка, приклеенная к мыши». Сведи постоянные —
   получится жёсткая пара кружков, ради которой не стоило заводить
   ни один слушатель.

   Единица здесь не доля за кадр, как у PLAN_EASE выше, а ПОСТОЯННАЯ
   ВРЕМЕНИ в миллисекундах: k = 1 − exp(−dt / tau). Доля за кадр —
   это скрытая привязка к 60 Гц, и на 120-герцевом ноутбуке тот же
   0,06 даёт вдвое более резкое слежение. Курсор живёт на экране
   постоянно, разница в скорости заметна сразу. */

