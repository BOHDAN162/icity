/* --- кривые CSS в JS -------------------------------------------------
   Часть движения на сайте гонит rAF, а не CSS: связка на карте, выезды
   кадров вида. Кривая при этом обязана совпадать с той, что стоит
   в токене, иначе одно и то же движение читается по-разному в разных
   местах. Отсюда безье прямо здесь — пятнадцать строк вместо
   зависимости.

   ПРАВЯТСЯ ПАРОЙ С app/tokens.css. Разъедутся числа — разъедется
   и характер движения, причём молча. */

export type Bezier = [number, number, number, number];

/** Копия `--ease-soft`: появления. */
export const EASE_SOFT: Bezier = [0.16, 1, 0.3, 1];
/** Копия `--ease-standard`: всё остальное, в том числе створки. */
export const EASE_STANDARD: Bezier = [0.4, 0, 0.2, 1];
/** Копия `--ease-view`: выезды кадров вида и счёт чисел. Симметричная. */
export const EASE_VIEW: Bezier = [0.65, 0, 0.35, 1];

/** Ньютон по x, затем значение по y. */
export function bezier([x1, y1, x2, y2]: Bezier) {
  const cx = 3 * x1;
  const bx = 3 * (x2 - x1) - cx;
  const ax = 1 - cx - bx;
  const cy = 3 * y1;
  const by = 3 * (y2 - y1) - cy;
  const ay = 1 - cy - by;
  const sampleX = (t: number) => ((ax * t + bx) * t + cx) * t;
  const slopeX = (t: number) => (3 * ax * t + 2 * bx) * t + cx;
  return (x: number) => {
    let t = x;
    for (let i = 0; i < 6; i += 1) {
      const d = slopeX(t);
      if (Math.abs(d) < 1e-6) break;
      t -= (sampleX(t) - x) / d;
    }
    t = Math.min(1, Math.max(0, t));
    return ((ay * t + by) * t + cy) * t;
  };
}
