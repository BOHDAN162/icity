/* iCITY 113Н — режим своего курсора.
   Путь в проекте: lib/cursorMode.ts

   Курсор один на весь сайт и живёт в layout, а просят его о другом виде
   экраны, лежащие глубоко в дереве: лист чертежа и ролик полёта. Канал
   тот же по устройству, что lib/officeZone.ts, — модульный объект,
   а не проп: прокидывать колбэк через шесть чужих секций нельзя, а
   useSyncExternalStore здесь не нужен, потому что читатель не React,
   а rAF-цикл внутри Cursor.tsx. Он и читает поля напрямую, каждый кадр.

   ФЛАГИ ИМЕНОВАННЫЕ, А НЕ ОДИН БУЛЕВ. Источников два, и они независимы:
   общий выключатель погас бы, когда первый источник отпустил, а второй
   ещё держит. Появится третий — здесь новое поле, а не «ну ещё один
   вызов setCursorDot»: перечисление на виду честнее умолчания. */

export type CursorMode = {
  /** Открыт лист чертежа. Кольцо там спорит с обмерными линиями, и его
      диаметр — половина подписи зоны: остаётся только точка. */
  sheet: boolean;
  /** Идёт ролик полёта: только точка, и она плавно белеет. */
  video: boolean;
  /* «Нарисуй кадр». Ставит Cursor, зовут отправители. Через эту щель,
     а не импортом: цикл курсора спит, пока ничего не едет, и без
     пробуждения смена режима просто не отрисовалась бы. */
  wake?: () => void;
};

export const cursorMode: CursorMode = { sheet: false, video: false };

const set = (key: 'sheet' | 'video', on: boolean) => {
  if (cursorMode[key] === on) return;
  cursorMode[key] = on;
  cursorMode.wake?.();
};

/** Лист чертежа открыт или закрыт. */
export const setCursorSheet = (on: boolean) => set('sheet', on);

/** Ролик полёта пошёл или кончился. */
export const setCursorVideo = (on: boolean) => set('video', on);
