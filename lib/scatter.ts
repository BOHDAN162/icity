/* iCITY 113Н — разброс задержек побуквенного проявления.
   Путь в проекте: lib/scatter.ts

   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ РАДИ ШЕСТИ СТРОК. Побуквенных проявлений
   на сайте два — заголовок первого экрана и подпись кадра вида, — и оба
   обязаны считать задержку одинаково. Скопировать функцию во второй
   файл было бы дешевле ровно один раз: дальше копии разъезжаются молча,
   а цена расхождения здесь — разъехавшаяся гидрация.

   ДЕТЕРМИНИРОВАННАЯ НАРОЧНО: сервер и клиент обязаны получить одно
   и то же число, иначе гидрация разъедется на каждой букве. Отсюда
   только 32-битная целочисленная арифметика — она специфицирована
   точно и одинакова во всех движках. Math.random() здесь нельзя
   вообще, а Math.sin() нельзя потому, что его последние биты
   у движков расходятся.

   Хеш обычный мультипликативный с xorshift: константа Кнута
   (золотое сечение) на входе, вторая из fmix32 на выходе. 997 —
   простое, чтобы остаток не ложился в короткий цикл на соседних
   индексах: буквы нумеруются подряд, и период вида 2^k дал бы
   видимую периодичность разброса. */

/** Псевдослучайная задержка буквы по её номеру, 0..1. */
export const scatter = (i: number): number => {
  let h = Math.imul(i + 1, 2654435761);
  h ^= h >>> 15;
  h = Math.imul(h, 2246822519);
  h ^= h >>> 13;
  return ((h >>> 0) % 997) / 997;
};
