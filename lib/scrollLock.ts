/* iCITY 113Н — замок прокрутки страницы.
   Путь в проекте: lib/scrollLock.ts

   ЗАЧЕМ УТИЛИТА, ЕСЛИ ЭТО ДВЕ СТРОКИ. Затем, что читателей у замка
   больше, чем ставящих, и одному из них нужно отличать СВОЙ замок
   от чужого. Пока замков было три (жив hero, открыт оверлей подвала,
   открыт план из офиса), все они означали одно: «экраном распоряжается
   кто-то другой, не трогай». Esc-тумблер планировки на этом и стоял —
   `if (document.body.style.overflow === 'hidden') return`.

   Четвёртый замок сломал это допущение. Секция офиса запирает страницу
   на время шаговых переходов к кадрам вида, и она же обязана оставаться
   местом, откуда Esc открывает кукольный дом. Сырой булев признак такое
   различить не может — отсюда владелец.

   МАРКЕР ПРЕЖНИЙ, И ЭТО НЕСУЩЕЕ ТРЕБОВАНИЕ. Замком по-прежнему служит
   инлайновый `body.style.overflow = 'hidden'`: его читают ScrollTrip
   (в onWheel, в цикле draw и в канале плавной прокрутки) прямо из
   стиля, без раскладки и без импорта. Заменишь маркер классом или
   data-атрибутом — чинить придётся там же. Владелец лежит рядом,
   отдельной переменной модуля, и на сам маркер не влияет.

   ВЛОЖЕННОСТИ НЕТ НАРОЧНО. Замок один на страницу, стек владельцев не
   нужен: сценариев, где hero и оверлей подвала живы одновременно,
   не существует — hero накрывает контент `inert`. Попытка запереть
   поверх чужого замка — это ошибка вызывающего, и она кричит в консоль
   в разработке, а не молча копит счётчик. */

/* Владельцы перечислены здесь, а не литералами по местам вызова:
   Esc-тумблер планировки сравнивает СВОЙ замок с чужим, и опечатка
   в строке дала бы не ошибку типов, а молча неработающий Esc. */

/** Жив первый экран: ролик полёта и кнопки входа. */
export const HERO_LOCK = 'hero';
/** Открыт «Чертёж» или «3D-модель» из подвала, у формы записи. */
export const CONTACT_LOCK = 'contact-overlay';
/** Открыт кукольный дом. */
export const PLAN_LOCK = 'plan';
/** Секция офиса ведёт шаговый переход к кадру вида. */
export const OFFICE_STEP_LOCK = 'office-step';

let owner: string | null = null;
/** Что стояло в инлайновом стиле до нас: чаще всего пустая строка. */
let prev = '';

/* Кому сообщать о смене владельца. Нужно ровно одному потребителю
   и ровно за одним: секция офиса запирает страницу, как только её
   отпустит hero, а никакого события в этот момент не происходит —
   свап hero страницу не двигает, значит ни scroll, ни resize
   не придут. Опрашивать в rAF ради одного перехода — расточительно,
   поэтому канал, как officeZone и cursorMode. */
const watchers = new Set<() => void>();

/** Подписка на «замок сменил владельца». */
export function onScrollLockChange(fn: () => void): () => void {
  watchers.add(fn);
  return () => {
    watchers.delete(fn);
  };
}

const notify = () => {
  for (const fn of watchers) fn();
};

/** Кто держит замок прямо сейчас, или null. */
export function scrollLockOwner(): string | null {
  return owner;
}

/** Заперта ли страница — кем угодно. Для тех, кому владелец безразличен. */
export function isScrollLocked(): boolean {
  return owner !== null;
}

/* Запереть страницу от имени владельца. Повторный вызов тем же
   владельцем безвреден: замок один, ставить его дважды нечем. */
export function lockScroll(by: string): void {
  if (owner === by) return;
  if (owner !== null) {
    if (process.env.NODE_ENV !== 'production') {
      console.error(`scrollLock: «${by}» запирает поверх «${owner}»`);
    }
    return;
  }
  owner = by;
  prev = document.body.style.overflow;
  document.body.style.overflow = 'hidden';
  notify();
}

/* Отпереть. Чужой замок не снимается — иначе размонтирование одного
   экрана отдавало бы прокрутку, которую держит другой. */
export function unlockScroll(by: string): void {
  if (owner !== by) return;
  owner = null;
  document.body.style.overflow = prev;
  prev = '';
  notify();
}
