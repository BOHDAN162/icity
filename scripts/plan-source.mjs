/* --- мебель -----------------------------------------------------------
   t: r прямоугольник · c круг · cab секционный шкаф · rail вешало
      hob плита · sink мойка · wc унитаз · fridge холодильник · tv экран
      door распашная дверь (петля + полотно + дуга)
   rr — скругление, a — поворот в градусах вокруг центра. */

const desks = () => {
  /* 26 мест блоками 4-6-6-6-4 — ровно то, что подсчитано в docs/facts.md.
     Границы блоков сняты проекцией серых линий растра по столбцам:
     все пять блоков вышли одной ширины 1,575 (два стола по 0,7875),
     все ряды — 1,377 в глубину. Ровность здесь настоящая, не подогнанная. */
  const X = [1.734, 4.996, 8.770, 12.718, 16.004];
  const ROWS = [[10.563, 11.933], [11.933, 13.323], [13.323, 14.700]];
  const N = [2, 3, 3, 3, 2];
  const W = 0.7875;
  const out = [];
  X.forEach((x0, b) => {
    for (let r = 0; r < N[b]; r += 1) {
      const [y0, y1] = ROWS[r];
      const h = y1 - y0;
      out.push({ z: 'openspace', t: 'r', x: x0, y: y0, w: W, h, rr: 0.05 });
      out.push({ z: 'openspace', t: 'r', x: x0 + W, y: y0, w: W, h, rr: 0.05 });
      // кресла с внешних сторон блока
      out.push({ z: 'openspace', t: 'r', x: x0 - 0.50, y: y0 + h / 2 - 0.26, w: 0.42, h: 0.52, rr: 0.10 });
      out.push({ z: 'openspace', t: 'r', x: x0 + 2 * W + 0.08, y: y0 + h / 2 - 0.26, w: 0.42, h: 0.52, rr: 0.10 });
    }
  });
  return out;
};

