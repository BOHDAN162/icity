'use client';

/* iCITY 113Н — приглашение листать вниз.
   Путь в проекте: components/ScrollCue.tsx

   ЧТО ЭТО. Слово со стрелкой-маятником под ним: «здесь кончилось,
   дальше листайте». Один вид на три места, и это не удобство, а условие:
   зритель, который идёт по сайту кнопками, должен встречать одно и то же
   приглашение — на кадре панорамы, на втором кадре вида и в самом офисе,
   под капсулой «Открыть планировку». Разъедутся видом — он решит,
   что это три разных органа управления.

   ЗДЕСЬ ТОЛЬКО ВИД. Где кнопка стоит и когда она видна — забота места:
   на кадрах это абсолютные координаты и признаки на сцене
   (OfficeStop.module.css), в офисе — ячейка грида (OfficeHub.module.css).
   Позиционирование приезжает классом снаружи.

   ТОН. На кадре панорамы под текстом общая вуаль и он графитовый;
   на втором кадре вуали нет вовсе, фото тёмное, и текст белый —
   замер там: графит 1,00:1 против белых 2,45 худших и 12,32 средних.

   МАЯТНИК ПОД КУРСОРОМ НЕ ОСТАНАВЛИВАЕТСЯ. Сначала стрелка замирала
   в нижней точке; заказчик посмотрел живьём 5 сентября 2026 и попросил
   оставить движение — остановка читалась как «кнопка сломалась» ровно
   в момент наведения. Ховер несут подпись и красная линия под ней. */

import { ArrowDown } from './NextCue';
import styles from './ScrollCue.module.css';

type Props = {
  onClick: () => void;
  /** позиционирование приезжает снаружи, из модуля места */
  className?: string;
  /** 'white' — для кадра без вуали под текстом */
  tone?: 'ink' | 'white';
  /** что назвать голосом: у офиса и кадров следующий экран разный */
  label?: string;
  /* СТРЕЛКА БЕЗ МАЯТНИКА. Ставится тому, кто ниже уже был и вернулся:
     звать его качанием туда, где он побывал, незачем, а сама кнопка
     нужна. Движение при этом не исчезает — оно ждёт наведения:
     под курсором стрелка плавно уходит вниз. */
  still?: boolean;
};

export default function ScrollCue({
  onClick, className = '', tone = 'ink', label, still = false,
}: Props) {
  return (
    <button
      type="button"
      className={[
        styles.cue,
        tone === 'white' ? styles.white : '',
        still ? styles.still : '',
        className,
      ].filter(Boolean).join(' ')}
      onClick={onClick}
      aria-label={label}
    >
      <span className={`label ${styles.label}`}>Листайте вниз</span>
      <span className={styles.arrow} aria-hidden="true"><ArrowDown size={18} /></span>
    </button>
  );
}
