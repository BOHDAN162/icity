import type { CSSProperties } from 'react';
import { requestNextStep } from '@/lib/officeZone';
import styles from './NextCue.module.css';

const REDUCED = '(prefers-reduced-motion: reduce)';

type Props = {
  /** Имя следующего экрана — приходит от OfficeStop, он им и владеет. */
  next: { title: string };
  /** Доля просмотренных зон, 0…1. Считает OfficeHub по своему seen. */
  progress: number;
};

/* Стрелка вниз. Тот же рисунок, что у кругов перехода в OfficeHub
   (M12 19V5…), развёрнутый: остриё внизу. Экспортируется — этой же
   стрелкой подписывается «все зоны просмотрены» в счётчике. */
export function ArrowDown({ size = 17 }: { size?: number }) {
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} aria-hidden="true">
      <path
        d="M12 5v14m0 0 6-6m-6 6-6-6"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.7"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

export default function NextCue({ next, progress }: Props) {
  const done = progress >= 1;

  const goDown = () => {
    /* Под prefers-reduced-motion шагов нет вовсе: офис и оба кадра —
       обычные экраны в потоке, и запирать нечего. Целимся прямо в кадр,
       мгновенно: ScrollTrip под этой настройкой не монтируется. */
    if (matchMedia(REDUCED).matches) {
      document.getElementById('view')?.scrollIntoView();
      return;
    }

    /* Кнопка просит ровно тот же шаг, что жест колеса, и просит его
       у того же хозяина — секции офиса. Своей прокрутки у неё больше
       нет: прежде она целилась в долю хода (VIEW_HOLD_P), а долей
       хода у шагов не существует. */
    requestNextStep();
  };

  return (
    <button
      type="button"
      className={[styles.cue, done ? styles.done : ''].filter(Boolean).join(' ')}
      /* Доля заливки. Инлайновым стилем, потому что источник — состояние
         React, а не переменная сцены; CSS-модулем такое не задать. */
      style={{ '--cue': progress } as CSSProperties}
      onClick={goDown}
      aria-label={`Дальше: ${next.title}`}
    >
      <span className={`label ${styles.railLabel}`}>Дальше</span>
      <span className={styles.rail} aria-hidden="true">
        <span className={styles.railFill} />
      </span>
      <span className={styles.railArrow} aria-hidden="true">
        <ArrowDown />
      </span>
    </button>
  );
}
