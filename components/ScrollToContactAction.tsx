'use client';

/* iCITY 113Н — кнопка «Записаться на просмотр» на экране 2.
   Путь в проекте: components/ScrollToContactAction.tsx

   Прокручивает страницу поездкой ScrollTrip (lib/motion.ts), а не
   мгновенным браузерным прыжком по #contact — тот читался как «сайт
   сразу показал форму». Цель одна на всех экранах: сама форма записи
   по центру экрана (разбор ниже).

   ЦЕЛЬ — НЕ ЧИСЛО, СНЯТОЕ ЗДЕСЬ. Прежде кнопка передавала scrollHeight
   на момент клика, а страница по дороге вниз растёт (кадр комплекса
   монтируется по IntersectionObserver, ниже подъезжают картинки) —
   цель оказывалась выше настоящей. Теперь цель живая, её пересчитывает
   сам цикл прокрутки на каждом кадре.

   href остаётся якорем, и preventDefault ставится ТОЛЬКО когда поездку
   действительно взяли. Не взяли (нет JS, prefers-reduced-motion,
   заперта страница) — клик уходит браузеру штатно, мгновенным прыжком
   к секции формы. Прежде отказ терялся молча, и клик не делал ничего:
   ровно то «иногда не срабатывает», на которое жаловался Богдан.

   ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Landing — серверный компонент (см. шапку
   CountUpScope.tsx), и обработчик клика клиентский по определению —
   вынесен в свою обёртку, а не тащит в клиентский бандл весь экран. */

import { requestSmoothScrollTo } from '@/lib/motion';

/* ЦЕЛЬ — ФОРМА ПО ЦЕНТРУ ЭКРАНА, А НЕ НИЗ СТРАНИЦЫ. Так на всех ширинах
   с 5 сентября 2026, и путь сюда был в два шага. Сперва кнопка везла
   в самый низ: расчёт был на то, что низ и есть нужный кадр — форма
   занимает его целиком, подвал под ней узкий. На узкой колонке это
   сломалось первым (форма уезжала за верхнюю кромку, в кадре стоял
   подвал), и телефону дали отдельную цель. Тем же вечером заказчик
   поймал ту же беду и на широком экране: под формой стоят блок
   контакта и подвал, и до низа поездка проезжает мимо. Развилки
   по ширине больше нет — цель одна.

   Цель ЖИВАЯ, функцией: пока идёт поездка, страница ниже кнопки растёт
   (кадр комплекса монтируется по IntersectionObserver, подъезжают
   картинки), и форма едет вместе с ней. Число, снятое на клике,
   промахнулось бы ровно на этот прирост.

   ЦЕЛИМСЯ В ФОРМУ ИЛИ В БЛОК УСПЕХА. После удачной отправки формы
   в DOM нет вовсе — на её месте стоит строка успеха, — и селектор
   по одной только форме ронял бы цель обратно в низ страницы, то есть
   ровно в то поведение, от которого уходим. Берём первый найденный
   из двух.

   Если цель выше экрана, центрировать нечего: прижимаем её верх
   к кромке с полем GAP_MIN. Не нашли ничего — возвращаем низ страницы:
   секции на странице может не быть вовсе. */
const GAP_MIN = 16;
/* Тот же адрес, что в href ниже. Константа CONTACT_ID живёт в Contact.tsx,
   но импортировать её отсюда нельзя: кнопка стоит на экране 2, и импорт
   утащил бы в её чанк весь модуль формы вместе с холстом и оверлеями. */
const CONTACT_ID = 'contact';

const centerContactForm = (): number => {
  const target = document.querySelector(`#${CONTACT_ID} form, #${CONTACT_ID} [role="status"]`);
  if (!target) return Number.POSITIVE_INFINITY;
  const rect = target.getBoundingClientRect();
  const gap = Math.max(GAP_MIN, (window.innerHeight - rect.height) / 2);
  return rect.top + window.scrollY - gap;
};

export default function ScrollToContactAction({ className }: { className: string }) {
  return (
    <a
      className={className}
      href="#contact"
      onClick={(e) => {
        if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
        if (requestSmoothScrollTo(centerContactForm)) e.preventDefault();
      }}
    >
      Записаться на просмотр
    </a>
  );
}
